"""The one redaction gate every write into Cortex storage passes through.

Storage substrates and where this gate sits on each (ADR-1110):

- SQL, both backends: the connection classes in ``sqlite_gated_connection``
  and ``pg_gated_cursor`` call :func:`redact_params` on the bound parameters
  of every write statement (:func:`is_write_statement`), whatever helper,
  pool or cursor issued it;
- embeddings: the embedding engine encodes :func:`redact_text` of its input,
  so no vector is derived from a secret;
- files: ``shared/gated_files`` writes only redacted text;
- logs: :class:`RedactingFilter` on every file handler.

Detection is the vendored gitleaks v8.30.1 rule set
(``redaction_rules/gitleaks.json``, provenance in
``third_party/gitleaks/v8.30.1/PROVENANCE.json``) applied by
``shared/redaction_engine``, followed by Cortex's own shapes
(``shared/redaction.redact_shapes``: URL passwords, ``Bearer`` values,
``password=``-style assignments, PEM blocks).

source: ADR-1110"""

from __future__ import annotations

import json
import logging
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

from mcp_server.shared.redaction import redact_shapes
from mcp_server.shared.redaction_engine import (
    RuleSet,
    compile_rule_set,
    redaction_spans,
    redact_spans,
)

# source: ADR-1110 — generated by scripts/vendor_gitleaks_rules.py
RULES_PATH = Path(__file__).with_name("redaction_rules") / "gitleaks.json"

# A statement writes when one of these verbs appears as a word anywhere in it
# (a common-table expression wrapping an UPDATE included). Reads are not gated:
# nothing they bind is persisted. source: ADR-1110
_WRITE_VERB = re.compile(r"\b(?:INSERT|UPDATE|REPLACE|MERGE|UPSERT|COPY)\b", re.I)


@lru_cache(maxsize=1)  # source: ADR-1110 — one rule set per process
def rule_set() -> RuleSet:
    """Load the vendored rule set once per process."""
    return compile_rule_set(json.loads(RULES_PATH.read_text(encoding="utf-8")))


# Prose pass: punctuation before whitespace, a quote or the end, blanked.
# Six gitleaks rules miss a key followed by it. source: ADR-1110 (Decision 2)
_SENTENCE_PUNCT = re.compile(r"[,.;:)\]}>!?]+(?=[\s\"'`]|$)")


def _prose_view(text: str) -> str:
    return _SENTENCE_PUNCT.sub(lambda m: " " * len(m.group()), text)


class RedactedText(str):
    """Text this process has already passed through :func:`redact_text`.

    Only ``redact_text`` builds one. Every operation on it (concatenation,
    slicing, formatting) returns a plain ``str``, so text derived from it is
    redacted again when it reaches the gate; the very same object is not. It
    does not cross a process boundary: a worker receives plain ``str`` over
    its socket and redacts it. source: ADR-1110 (review of PR #775, N2)"""

    __slots__ = ()


def redact_text(text: str) -> str:
    """Return ``text`` with every detected secret replaced by a marker."""
    if not text or type(text) is RedactedText:
        return text
    rules = rule_set()
    spans = redaction_spans(text, rules)
    view = _prose_view(text)
    if view != text:
        spans += redaction_spans(view, rules)
    return RedactedText(redact_shapes(redact_spans(text, spans)))


def redact_value(value: Any) -> Any:
    """Redact strings inside ``value``; containers keep their type.

    Bytes, numbers, dates and arrays carry no text and pass unchanged."""
    if isinstance(value, str):
        return redact_text(value)
    if isinstance(value, dict):
        return {k: redact_value(v) for k, v in value.items()}
    if isinstance(value, list):
        return [redact_value(v) for v in value]
    if isinstance(value, tuple):
        return tuple(redact_value(v) for v in value)
    return value


def is_write_statement(sql: str) -> bool:
    """True when ``sql`` can persist the parameters bound to it."""
    return bool(_WRITE_VERB.search(sql))


def redact_script(sql: str) -> str:
    """A SQL script carries its values inline: redact the text of a script
    that writes; a read-only script passes unchanged."""
    return redact_text(sql) if is_write_statement(sql) else sql


def redact_params(sql: str, params: Any) -> Any:
    """Redact bound parameters of a write statement; reads pass unchanged."""
    if params is None or not is_write_statement(sql):
        return params
    return redact_value(params)


class RedactingFilter(logging.Filter):
    """Rewrite each record's message through the gate before a handler writes."""

    def filter(self, record: logging.LogRecord) -> bool:
        message = record.getMessage()
        redacted = redact_text(message)
        if redacted != message:
            record.msg, record.args = redacted, None
        if record.exc_info and not record.exc_text:
            # Formatter.format reuses exc_text when set: the traceback text
            # (which can quote a failing value) is gated too.
            record.exc_text = logging.Formatter().formatException(record.exc_info)
        if record.exc_text:
            record.exc_text = redact_text(record.exc_text)
        if record.stack_info:
            record.stack_info = redact_text(record.stack_info)
        return True
