"""Permanent guard: no CI definition may compare a pull request with main.

Owner rule, 2026-10-29, verbatim: "je veux plus la revoir À VIE".

A check that reads main's tip (a merge-base against it, a branch update, a
rendered-output comparison between head and base, a strict "up to date"
protection, a workflow definition authorized against main, or a generated header
that carries a hash) makes every open pull request stale each time main moves.
This test fails when any of those traces returns to the CI definitions below.

Not covered on purpose: the diff perimeter `origin/$BASE_REF...$HEAD_SHA`, a
`merge-base --is-ancestor` safety check before a deletion, the `headRefOid` of the
reviewed pull request and a SHA cited as provenance. The confirmation that a merged
commit is in main's history and the publication of tags on a push to main are NOT
exceptions any more: a tag goes on the commit the push event built (github.sha).

Standard library only. This file is delivered to consuming repositories by
`render-ci --native-review`; it ignores every file with its own name.
"""

from pathlib import Path
import re
import unittest

ROOT = Path(__file__).resolve().parents[2]
DIRECTORIES = ("scripts", ".github/workflows")
GUARD = "test_no_main_comparison.py"
HEADER = "# generated by zetetic-team-subagents render-ci"
# The first four are written in two parts so that no search for the removed
# workflow-definition proof finds this guard instead of a regression.
FORBIDDEN = (
    "authorize" + "_workflow",
    "workflow proof" + " definition",
    "WORKFLOW" + "_PROOF",
    "ci_workflow" + "_proof",
    "workflow_pr_perime",
    "update-branch",
    "update_branch",
    "merge-base HEAD origin/main",
    "render_head != render_base",
    "compare/main",
    "refs/remotes/origin/main^{commit}",
    "differs from trusted main",
    "_confirm_main_merge",
)
PATTERNS = (
    # blob(...) in the generated header changes every consumer's bytes per render.
    (re.compile(r"header\s*\+\s*blob\("), "blob( in the generated header"),
    # A variable that carries main's tip into a decision.
    (re.compile(r"\b(?:MAIN|TRUSTED)_SHA\b", re.IGNORECASE), "a SHA of main kept in a variable"),
)
# `strict: true` requires the branch to be up to date with main. It is forbidden only
# in a branch-protection configuration; other files may use the word freely.
STRICT = re.compile(r"\"strict\"\s*:\s*true|\bstrict:\s*true\b")
PROTECTION = re.compile(r"required_status_checks|branches/[^\s\"']*/protection")


def scanned(root, directories):
    """Yield every text file under `directories` except this guard."""
    for directory in directories:
        for path in sorted((Path(root) / directory).rglob("*")):
            skipped = path.name == GUARD or {"__pycache__", "node_modules"} & set(path.parts)
            if path.is_file() and not skipped:
                yield path


def traces(line, protection):
    """Return the forbidden traces on one line."""
    found = [token for token in FORBIDDEN if token in line]
    found += [name for pattern, name in PATTERNS if pattern.search(line)]
    if protection and STRICT.search(line):
        found.append('"strict": true in a protection config')
    if line.startswith("# generated by ") and line.rstrip() != HEADER:
        found.append("generated header with a hash: " + line)
    return found


def violations(root=ROOT, directories=DIRECTORIES):
    """Return `path:line: token` for every forbidden trace under `directories`."""
    found = []
    for path in scanned(root, directories):
        text = path.read_text(encoding="utf-8", errors="ignore")
        protection = PROTECTION.search(text) is not None
        for number, line in enumerate(text.splitlines(), 1):
            found += [f"{path.relative_to(root)}:{number}: {x}" for x in traces(line, protection)]
    return found


class NoMainComparison(unittest.TestCase):
    def test_no_definition_compares_with_main(self):
        self.assertEqual(violations(), [], "owner rule 2026-10-29: never compare with main")


if __name__ == "__main__":
    unittest.main()
