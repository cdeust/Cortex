"""Baseline load/save/diff for the craftsmanship gate.

The baseline is a file committed in the same tree as the code it
describes: the measure of the working tree must be at most that baseline,
and a PR that improves the measure lowers the baseline in its own diff.

source: ADR-0720"""

from __future__ import annotations

import datetime as _dt
import json
import sys
from collections import Counter
from pathlib import Path

_SCRIPTS_DIR = str(Path(__file__).resolve().parent)
if _SCRIPTS_DIR not in sys.path:
    sys.path.insert(0, _SCRIPTS_DIR)
from craftsmanship_rules import Violation  # noqa: E402


def parse_baseline_json(text: str) -> set[Violation]:
    """Parse a baseline JSON document's ``violations`` array."""
    data = json.loads(text)
    return {
        Violation(entry["file"], entry["kind"], entry["detail"])
        for entry in data.get("violations", [])
    }


def load_baseline(path: Path) -> set[Violation]:
    """Return the baselined violations, or an empty set if none exists yet."""
    if not path.exists():
        return set()
    return parse_baseline_json(path.read_text(encoding="utf-8"))


def save_baseline(path: Path, violations: set[Violation]) -> None:
    """Write ``violations`` as the new baseline, sorted for a stable diff."""
    entries = sorted(
        ({"file": v.file, "kind": v.kind, "detail": v.detail} for v in violations),
        key=lambda entry: (entry["file"], entry["kind"], entry["detail"]),
    )
    payload = {
        "$comment": (
            "Generated by `python scripts/check_craftsmanship.py --write-baseline`. "
            "Do NOT add an entry by hand to silence a new violation — that is "
            "gaming the ratchet, not maintaining it "
            "(docs/agent-guidance.md § Code Style). "
            "Regenerate only after confirming every new entry is pre-existing "
            "debt, not something this PR just introduced. Every entry removed "
            "here must correspond to a violation actually fixed in the code."
        ),
        "generated": _dt.datetime.now(tz=_dt.timezone.utc).date().isoformat(),
        "violations": entries,
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def new_violations(
    current: set[Violation], baseline: set[Violation]
) -> list[Violation]:
    """Violations present now but absent from the baseline — these block."""
    return sorted(current - baseline, key=lambda v: (v.file, v.kind, v.detail))


def stale_entries(
    baseline: set[Violation], rescanned: dict[str, set[Violation]]
) -> list[Violation]:
    """Baseline entries whose violation no longer exists in the current code.

    source: ADR-0720"""
    stale = [
        entry for entry in baseline if entry not in rescanned.get(entry.file, set())
    ]
    return sorted(stale, key=lambda v: (v.file, v.kind, v.detail))


def count_by_kind(violations: set[Violation] | list[Violation]) -> dict[str, int]:
    """Debt breakdown by rule family — printed on ``--write-baseline`` so a
    1000+-entry baseline is a visible number per rule, not an opaque wall
    of JSON no reviewer will actually read end to end.
    """
    return dict(sorted(Counter(v.kind for v in violations).items()))
